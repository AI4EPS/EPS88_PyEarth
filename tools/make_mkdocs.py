#!/usr/bin/env python
"""Generate mkdocs.yml from course.yml.

The previous repo's nav was hand-written and pinned to a structure that no longer existed —
eleven entries pointing at notebooks that had been replaced. Generating it means the site
cannot drift from the plan.
"""
import pathlib, yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
course = yaml.safe_load((ROOT / "course.yml").read_text())

# Only notebooks course.yml says are RELEASED. Every week exists on the builder's disk
# and only the released ones are on main, so an existence check would generate one thing
# here and another on CI — which is exactly what generated_is_current() fails on.
RELEASED = set(course["policy"].get("notebooks_released", []))


# SCHEDULE.md lives at the repo root, outside docs_dir, so a nav entry for it 404s on the
# built site. docs/README.md already carries the week table for students.
# Weeks and practice notebooks in one list, ordered the way a student meets them — `after: 1`
# on a practice entry slots it between weeks 1 and 2. A nav section of its own reads as optional
# extra material, which is the opposite of what it is.
# Only what actually exists on disk: listing all fourteen makes mkdocs fail on the missing files
# and publishes dead links for weeks nobody has built yet.
practice = [pr for pr in course.get("practice", [])
            if pr["slug"] in RELEASED]
items = ([(s["n"], f'Week {s["n"]}: {s["question"]}', s["slug"]) for s in course["schedule"]
          if s["modules"] and s["slug"] in RELEASED]
         + [(pr["after"] + 0.5, pr["title"], pr["slug"]) for pr in practice])
items.sort(key=lambda i: i[0])

nav = ["  - Home: README.md", "  - Weeks:"]
nav += [f'    - "{label}": notebooks/{slug}.ipynb' for _sort, label, slug in items]

# Answer keys, and ONLY the ones course.yml says are released. Every other *_solution.ipynb is
# gitignored, absent on CI, and excluded below — three independent reasons it cannot reach the
# site, which is the point: this is the file that would leak the term in one click.
released = list(course["policy"].get("solutions_released", []))
titles = {s["slug"]: f'Week {s["n"]}' for s in course["schedule"]}
titles.update({pr["slug"]: pr["title"] for pr in course.get("practice", [])})
shown = [r for r in released
         if (ROOT / "docs" / "notebooks" / f"{r}_solution.ipynb").exists()]
if shown:
    nav.append("  - Solutions:")
    for r in shown:
        nav.append(f'    - "{titles.get(r, r)} — solutions": notebooks/{r}_solution.ipynb')

# Project tracks. They are published from the start of the term — course.yml's `choose:` says
# the track notebooks ARE the spec and a student can read ahead — so an unnavigable track is a
# track nobody can choose. Same guard as the weeks: only what exists on disk.
tracks = sorted(r for r in RELEASED if r.startswith("T"))
if tracks:
    nav.append("  - Projects:")
    by_id = {t["id"]: t for t in course["project"]["tracks"]}
    for stem in tracks:
        tid = stem.split("_")[0]
        title = by_id.get(tid, {}).get("title", stem)
        nav.append(f'    - "{tid}: {title}": notebooks/{stem}.ipynb')

# Default-deny EVERY notebook, then re-admit the released ones by name. mkdocs reads exclude_docs
# with gitignore syntax, negation included (verified against mkdocs 1.6.1 before this was written).
#
# On CI an unreleased notebook is absent, so this changes nothing there. It matters the day
# somebody runs `mkdocs gh-deploy` from a laptop, where every week of the term is on disk: mkdocs
# copies everything under docs_dir whether it is in the nav or not, so without this the whole
# course — thirteen weeks and every answer key — goes to the web at guessable URLs. The same hole
# the solution exclusion was written to close, one directory wider.
exclude = "\n".join(["  notebooks/*.ipynb"]
                    + [f"  !notebooks/{r}.ipynb" for r in sorted(RELEASED)]
                    + [f"  !notebooks/{r}_solution.ipynb" for r in released])

(ROOT / "mkdocs.yml").write_text(f"""# GENERATED by tools/make_mkdocs.py from course.yml. Do not edit.
site_name: "EPS 88 — PyEarth: A Python Introduction to Earth Science"
site_author: "{course['instructor'].split('<')[0].strip()}"
docs_dir: docs/

# A solution notebook is NOT in the nav, but mkdocs publishes everything under docs_dir whether
# it is navigable or not — a --strict build copied all thirteen into the site, at guessable
# URLs. On CI they are absent (gitignored), so nothing leaked; the day one is released with
# `git add -f`, or the day anyone runs gh-deploy from a laptop, every remaining solution goes
# with it. Exclusion is the only thing standing between the release policy and the web.
exclude_docs: |
{exclude}
repo_name: "{course['platform']['repo'].split('github.com/')[-1]}"
repo_url: "{course['platform']['repo']}"

theme:
  name: material
  features: [navigation.sections, content.code.copy]

plugins:
  - search
  - mkdocs-jupyter:
      include_source: true

nav:
{chr(10).join(nav)}
""")
n_weeks = len(items)
n_tracks = sum(1 for l in nav if l.strip().startswith('- "T'))
print(f"mkdocs.yml — {n_weeks} weeks, {n_tracks} project track(s), "
      f"{len(practice)} practice, {len(shown)} released solution(s) in nav")
